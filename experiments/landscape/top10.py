#!/usr/bin/env python
"""Pick the k best-improving well-fit gauges from a landscape census and
write two ready-to-run n-q landscape bundles for them (nse-batch and kge
objectives).

Reads `<census_dir>/<arm>/summary.csv` (one row per gauge per arm, written by
`src/experiment/landscape/mod.rs::append_summary` — see
`src/experiment/adjoint/output.rs:264`) for every arm listed in
`<census_dir>/manifest.json`. "Well-fit" means `nse0 >= --nse-min`; among
those, keeps the `--k` gauges with the largest `nse_star - nse0` gain. If a
staid appears in more than one arm's summary.csv, the row with the larger
gain is kept.

Writes:
    experiments/<prefix>-nse/experiment.yaml   (objective: nse-batch)
    experiments/<prefix>-kge/experiment.yaml   (objective: kge)
    experiments/<prefix>_selection.csv

Both bundles select the SAME staids (chosen by NSE gain); only `objective`
differs. Both are copied from experiments/landscape-p21-surface-nq/experiment.yaml
(arms block kept verbatim) with the gauges block replaced by
`source: list` / `staids: [...]`, and:
    series: true, grid: 25, planes: ["n-q"], slice_center: trained,
    water_year: 1996, window_days: 1826, n_windows: 1

Usage:
    ~/projects/ddr/.venv/bin/python experiments/landscape/top10.py \\
        <merged-census-dir> [--k 10] [--nse-min 0.3] --out experiments/<bundle-prefix>
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

TEMPLATE = Path(__file__).resolve().parent.parent / "landscape-p21-surface-nq" / "experiment.yaml"

SELECTION_COLUMNS = ["staid", "arm", "n_reach", "nse0", "nse_star", "gain", "mult_n", "mult_q"]


def load_summary_rows(census_dir: Path) -> list[dict]:
    manifest = json.loads((census_dir / "manifest.json").read_text())
    arm_names = [a["name"] for a in manifest["arms"]]
    rows: list[dict] = []
    for arm in arm_names:
        path = census_dir / arm / "summary.csv"
        if not path.exists():
            print(f"warning: {path} does not exist, skipping arm {arm!r}")
            continue
        with path.open(newline="") as f:
            for row in csv.DictReader(f):
                rows.append(row)
    if not rows:
        raise SystemExit(f"no summary.csv rows found under {census_dir} for arms {arm_names}")
    return rows


def select_top_k(rows: list[dict], k: int, nse_min: float) -> list[dict]:
    """Best row (max gain) per staid, restricted to nse0 >= nse_min, top k by gain."""
    best: dict[str, dict] = {}
    for row in rows:
        staid = row["staid"]
        nse0 = float(row["nse0"])
        nse_star = float(row["nse_star"])
        if nse0 < nse_min:
            continue
        gain = nse_star - nse0
        cur = best.get(staid)
        if cur is None or gain > cur["gain"]:
            best[staid] = dict(
                staid=staid,
                arm=row["arm"],
                n_reach=int(row["n_reach"]),
                nse0=nse0,
                nse_star=nse_star,
                gain=gain,
                mult_n=float(row["mult_n"]),
                mult_q=float(row["mult_q"]),
            )
    ranked = sorted(best.values(), key=lambda r: r["gain"], reverse=True)
    return ranked[:k]


def print_table(selection: list[dict]) -> None:
    header = f"{'staid':>10}  {'n_reach':>7}  {'nse0':>7}  {'nse_star':>8}  {'gain':>7}  {'mult_n':>8}  {'mult_q':>8}"
    print(header)
    print("-" * len(header))
    for r in selection:
        print(
            f"{r['staid']:>10}  {r['n_reach']:>7d}  {r['nse0']:>7.3f}  {r['nse_star']:>8.3f}  "
            f"{r['gain']:>7.3f}  {r['mult_n']:>8.3f}  {r['mult_q']:>8.3f}"
        )


def write_selection_csv(selection: list[dict], out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=SELECTION_COLUMNS)
        writer.writeheader()
        for r in selection:
            writer.writerow({c: r[c] for c in SELECTION_COLUMNS})


def extract_arms_block(template_text: str) -> str:
    """Return the verbatim `arms:` ... block (up to, not including,
    `landscape:`) from the template file, so the arm/run/checkpoint pin
    travels unchanged into the derived bundles."""
    lines = template_text.splitlines(keepends=True)
    start = next(i for i, l in enumerate(lines) if l.startswith("arms:"))
    end = next(i for i, l in enumerate(lines) if l.startswith("landscape:"))
    return "".join(lines[start:end])


def write_bundle(
    out_dir: Path,
    arms_block: str,
    staids: list[str],
    objective: str,
    census_dir: Path,
    k: int,
    nse_min: float,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    staids_yaml = "\n".join(f'      - "{s}"' for s in staids)
    header = (
        f"# Auto-generated by experiments/landscape/top10.py from census {census_dir}.\n"
        f"# Selection rule: nse0 >= {nse_min}, top {k} by (nse_star - nse0), objective {objective}.\n"
        f"# n-q terrain + daily series for the top-improving well-fit gauges.\n"
        f"#   target/release/ddrs --workspace .ddrs experiment {out_dir.name} --backend cpu\n"
    )
    body = (
        "study: landscape\n"
        f"{arms_block}"
        "landscape:\n"
        "  gauges:\n"
        "    source: list\n"
        "    staids:\n"
        f"{staids_yaml}\n"
        "  window_days: 1826   # 5 water years\n"
        "  water_year: 1996\n"
        "  n_windows: 1\n"
        "  alpha_max: 1.5\n"
        "  grid: 25\n"
        "  fd_step: 0.05\n"
        "  newton_iters: 12\n"
        "  tolerances: [0.05, 0.10]\n"
        "  max_clamped: 0.05\n"
        "  planes: [\"n-q\"]\n"
        "  slice_center: trained\n"
        f"  objective: {objective}\n"
        "  series: true\n"
    )
    (out_dir / "experiment.yaml").write_text(header + body)
    print(f"wrote {out_dir / 'experiment.yaml'}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("census_dir", type=Path, help="merged (or single) landscape census run directory")
    ap.add_argument("--k", type=int, default=10)
    ap.add_argument("--nse-min", type=float, default=0.3)
    ap.add_argument("--out", type=Path, required=True, help="bundle path prefix, e.g. experiments/landscape-p21-top10")
    args = ap.parse_args()

    if not TEMPLATE.exists():
        raise SystemExit(f"template not found: {TEMPLATE}")
    template_text = TEMPLATE.read_text()
    arms_block = extract_arms_block(template_text)

    rows = load_summary_rows(args.census_dir)
    selection = select_top_k(rows, args.k, args.nse_min)
    if not selection:
        raise SystemExit(f"no gauges with nse0 >= {args.nse_min} found in {args.census_dir}")
    if len(selection) < args.k:
        print(f"warning: only {len(selection)} gauges met nse0 >= {args.nse_min} (requested k={args.k})")

    print(f"selected {len(selection)} gauge(s) from {args.census_dir} (nse0 >= {args.nse_min}, ranked by nse_star - nse0):")
    print_table(selection)

    staids = [r["staid"] for r in selection]
    prefix = args.out.name
    out_root = args.out.parent
    write_bundle(out_root / f"{prefix}-nse", arms_block, staids, "nse-batch", args.census_dir, args.k, args.nse_min)
    write_bundle(out_root / f"{prefix}-kge", arms_block, staids, "kge", args.census_dir, args.k, args.nse_min)
    write_selection_csv(selection, out_root / f"{prefix}_selection.csv")
    print(f"wrote {out_root / f'{prefix}_selection.csv'}")


if __name__ == "__main__":
    main()
