"""Zero-step training-years replays of the working recipe on two other Q' stores (same config as seed 42 except the
streamflow store), for honest ensemble weights and multipliers: testing window 1985/10/01..1995/09/30.
  lstm_trainyears : 2026-09-13T13-55-03Z (daily_lstm_merit_unit_catchments.ic)
  dist_trainyears : 2026-09-13T17-22-30Z (daily_dhbv2_distributed_aorc2f ... _rechunked.ic)
"""
import json
import pathlib
import re

RUNS = pathlib.Path("/home/tbindas/projects/ddrs/.ddrs/runs")
HERE = pathlib.Path(__file__).resolve().parent
for name, rid in {"lstm_trainyears": "2026-09-13T13-55-03Z-train-and-test",
                  "dist_trainyears": "2026-09-13T17-22-30Z-train-and-test"}.items():
    ck = RUNS / rid / "checkpoints" / "epoch_50_mb_9"
    st = json.load(open(ck / "state.json"))
    assert st["epoch"] == 50 and st["next_mini_batch"] == 10 and st["sampler_cursor"] == 2365, (name, st["epoch"])
    assert not (RUNS / rid / "checkpoints" / "epoch_50_mb_10").exists()
    txt = (RUNS / rid / "config.yaml").read_text()
    txt, k = re.subn(r"\n  epochs: 50(\s)", f"\n  checkpoint: {ck}\n  epochs: 50\\1", txt, count=1)
    assert k == 1, name
    old_t = "testing:\n  start_time: 1995/10/01\n  end_time: 2010/09/30\n"
    assert txt.count(old_t) == 1, name
    txt = txt.replace(old_t, "testing:\n  start_time: 1985/10/01\n  end_time: 1995/09/30\n", 1)
    hdr = (f"# levers replay {name}: zero-step replay of {rid} epoch_50_mb_9, testing 1985/10/01..1995/09/30.\n"
           f"# Generated by experiments/levers/make_store_configs.py; otherwise the run's snapshot verbatim.\n")
    (HERE / f"replay_{name}.yaml").write_text(hdr + txt)
    print("wrote", name, "streamflow:", re.search(r"streamflow: (\S+)", txt).group(1))
