"""Zero-step replay configs for the queue (see queue.sh). Each is the source run's config.yaml snapshot verbatim plus
experiment.checkpoint (a checkpoint whose sampler is exhausted: next_mini_batch 10, cursor 2365), experiment.epochs set
to that checkpoint's epoch (so Phase 1 takes zero optimizer steps), and the testing window below.

  s42_e{10,25,40}_test5y : seed 42 no-dam, intermediate checkpoints, WY1996-2000 (the source run's own first five test
                           years, same cold-start date, so epoch 50 is read from the source run's predictions)
  g0_trainyears          : the gamma = 0, n+p+q recipe (2026-09-12T03-53-34Z), last checkpoint, 1981/10/01..1996/09/30
"""
import json
import pathlib
import re

RUNS = pathlib.Path("/home/tbindas/projects/ddrs/.ddrs/runs")
HERE = pathlib.Path(__file__).resolve().parent
JOBS = {
    "s42_e10_test5y": ("2026-09-27T07-29-47Z-train-and-test", 10, "1995/10/01", "2000/09/30"),
    "s42_e25_test5y": ("2026-09-27T07-29-47Z-train-and-test", 25, "1995/10/01", "2000/09/30"),
    "s42_e40_test5y": ("2026-09-27T07-29-47Z-train-and-test", 40, "1995/10/01", "2000/09/30"),
    "g0_trainyears": ("2026-09-12T03-53-34Z-train-and-test", 50, "1981/10/01", "1996/09/30"),
}
for name, (rid, ep, t0, t1) in JOBS.items():
    ck = RUNS / rid / "checkpoints" / f"epoch_{ep}_mb_9"
    st = json.load(open(ck / "state.json"))
    assert st["epoch"] == ep and st["next_mini_batch"] == 10 and st["sampler_cursor"] == 2365, (name, st["epoch"])
    assert not (RUNS / rid / "checkpoints" / f"epoch_{ep}_mb_10").exists()
    txt = (RUNS / rid / "config.yaml").read_text()
    txt, k = re.subn(r"\n  epochs: 50(\s)", f"\n  checkpoint: {ck}\n  epochs: {ep}\\1", txt, count=1)
    assert k == 1, name
    old_t = "testing:\n  start_time: 1995/10/01\n  end_time: 2010/09/30\n"
    assert txt.count(old_t) == 1, name
    txt = txt.replace(old_t, f"testing:\n  start_time: {t0}\n  end_time: {t1}\n", 1)
    hdr = (f"# levers replay {name}: zero-step replay of {rid} checkpoint epoch_{ep}_mb_9, testing {t0}..{t1}.\n"
           f"# Generated by experiments/levers/make_ckpt_configs.py; otherwise the run's snapshot verbatim.\n")
    (HERE / f"replay_{name}.yaml").write_text(hdr + txt)
    print("wrote", name)
