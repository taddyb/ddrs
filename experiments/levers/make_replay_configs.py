"""Write zero-step replay configs that score the no-dam full-population checkpoints on the TRAINING years.

Each config is the source run's config.yaml snapshot verbatim, plus:
  experiment.checkpoint: the run's last checkpoint (epoch_50_mb_9, sampler cursor 2365 of 2365), epochs unchanged (50),
    so Phase 1 takes zero optimizer steps and Phase 2 tests exactly that checkpoint (src/cli/run.rs Phase 2 fallback);
  testing window 1981/10/01 .. 1996/09/30: the training years (WY1982-1995) plus WY1996, which overlaps the source run's
    own test window and validates the replay against the source run's predictions.
"""
import pathlib

RUNS = pathlib.Path("/home/tbindas/projects/ddrs/.ddrs/runs")
HERE = pathlib.Path(__file__).resolve().parent
SRC = {42: "2026-09-27T07-29-47Z-train-and-test", 43: "2026-09-27T10-31-30Z-train-and-test"}

for seed, rid in SRC.items():
    txt = (RUNS / rid / "config.yaml").read_text()
    ck = RUNS / rid / "checkpoints" / "epoch_50_mb_9"
    assert (ck / "head.mpk").exists()
    old_ep = "  epochs: 50   #"
    assert txt.count(old_ep) == 1
    txt = txt.replace(old_ep, f"  checkpoint: {ck}\n  epochs: 50   #", 1)
    old_t = "testing:\n  start_time: 1995/10/01\n  end_time: 2010/09/30\n"
    assert txt.count(old_t) == 1
    txt = txt.replace(old_t, "testing:\n  start_time: 1981/10/01\n  end_time: 1996/09/30\n", 1)
    hdr = (f"# levers_replay_trainyears_s{seed}: zero-step replay of {rid} (checkpoint epoch_50_mb_9)\n"
           f"# scored on 1981/10/01..1996/09/30 (training years + WY1996 overlap). Generated by\n"
           f"# experiments/levers/make_replay_configs.py; everything below is the run's snapshot except those two edits.\n")
    out = HERE / f"replay_trainyears_s{seed}.yaml"
    out.write_text(hdr + txt)
    print("wrote", out)
